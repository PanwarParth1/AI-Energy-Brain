"""What-If Simulation service: thin orchestration over
ml.machine_health.simulate - no perturbation logic, feature extraction,
or model inference is reimplemented here.

Reuses machine_service's existing cached sensors dict (section 13 of
the Part 12 spec: avoid reloading the ~540MB raw dataset per request).
"""

from __future__ import annotations

import logging

from backend.app.core.config import settings
from backend.app.core.errors import bad_request
from backend.app.services import machine_service
from ml.recommendation.engine import generate_recommendations
from ml.machine_health.simulate import (
    PERTURBABLE_SENSORS,
    VALID_MODES,
    Perturbation,
    SimulationValidationError,
    analyze_simulated_machine,
)


logger = logging.getLogger(__name__)

RECOMMENDATION_NOTE = (
    "Scenario-specific decision support generated by the existing Part 9 rule engine from the "
    "SIMULATED health and anomaly outputs. It is not a diagnosis of a real machine, an anomaly is "
    "not a confirmed failure, and recommendations do not guarantee prevention of downtime. "
    "Persistence across recent real cycles is not applied, because a what-if scenario has no "
    "real history."
)
_SCENARIO_LIMITATION = (
    "Based on a hypothetical what-if scenario (modified sensor inputs), not a live measurement."
)


def build_scenario_recommendations(simulated: dict) -> list[dict]:
    """Integration layer: hand the SIMULATED Part 7 + Part 8 outputs to the existing,
    unmodified Part 9 engine. No rules are duplicated or added here.

    cycle_index is deliberately None: the engine's persistence rule looks up the REAL
    anomaly history of a real cycle, which a hypothetical scenario does not have, so
    passing the baseline cycle would credit the scenario with history it never had.
    """
    recs = generate_recommendations(
        health_result=simulated["health"],
        anomaly_result=simulated["anomaly"],
        cycle_index=None,
    )
    out = []
    for rec in recs:
        item = rec.to_dict()
        item["limitations"] = [*item["limitations"], _SCENARIO_LIMITATION]
        out.append(item)
    return out


def get_simulatable_sensors() -> dict:
    return {
        "sensors": PERTURBABLE_SENSORS,
        "excluded_virtual_sensors": ["CE", "CP", "SE"],
        "valid_modes": list(VALID_MODES),
        "note": (
            "CE, CP and SE are computed/derived channels in the source dataset, "
            "not independent physical inputs - they are excluded from what-if "
            "simulation. See ml/machine_health/simulate.py for the full reasoning."
        ),
    }


def run_simulation(machine_id: str, baseline_cycle_index: int, perturbations: list[dict]) -> dict:
    machine_service.validate_machine_id(machine_id)
    machine_service.validate_cycle_index(baseline_cycle_index)

    try:
        perturbation_objs = [
            Perturbation(sensor=p["sensor"], mode=p["mode"], value=p["value"]) for p in perturbations
        ]
        sensors = machine_service._get_sensors()  # cached - never reloaded per request
        result = analyze_simulated_machine(sensors, baseline_cycle_index, perturbation_objs)
    except SimulationValidationError as e:
        raise bad_request(str(e))

    result["machine_id"] = machine_id

    # Part 18: recommendations for the simulated scenario. A rule-engine failure must not
    # discard an otherwise valid simulation, so it is reported in its own field instead.
    try:
        result["recommendations"] = build_scenario_recommendations(result["simulated"])
        result["recommendations_error"] = None
    except Exception:  # noqa: BLE001 - reported to the client, logged with traceback
        logger.exception("Scenario recommendation generation failed")
        result["recommendations"] = None
        result["recommendations_error"] = "Unable to generate recommendations for this scenario."
    result["recommendation_note"] = RECOMMENDATION_NOTE
    return result
